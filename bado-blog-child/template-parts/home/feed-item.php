<?php
/** A single item in the mixed community feed. */
if ( ! defined( 'ABSPATH' ) ) {
    exit;
}
$item = $args['item'] ?? null;
if ( ! $item ) {
    return;
}
$author = oss_community_feed_author( $item['author_id'] );
?>
<article class="oss-feed-item oss-feed-<?php echo esc_attr( $item['type'] ); ?>">
    <div class="oss-feed-meta">
        <span class="oss-feed-type"><?php echo esc_html( $item['label'] ); ?></span>
        <time datetime="<?php echo esc_attr( gmdate( 'c', $item['time'] ) ); ?>"><?php echo esc_html( wp_date( 'd/m/Y · H:i', $item['time'] ) ); ?></time>
    </div>
    <h3><a href="<?php echo esc_url( $item['url'] ); ?>"><?php echo esc_html( $item['title'] ); ?></a></h3>
    <?php if ( $item['excerpt'] ) : ?>
        <p class="oss-feed-excerpt"><?php echo esc_html( $item['excerpt'] ); ?></p>
    <?php endif; ?>
    <?php if ( 'status' === $item['type'] && ! empty( $item['image_ids'] ) ) : ?>
        <div class="oss-feed-gallery" aria-label="Ảnh đính kèm trạng thái">
            <?php foreach ( array_slice( wp_parse_id_list( $item['image_ids'] ), 0, 4 ) as $image_id ) :
                if ( 'image/png' !== get_post_mime_type( $image_id ) ) {
                    continue;
                }
                $image = wp_get_attachment_image( $image_id, 'large', false, array( 'class' => 'oss-feed-image', 'loading' => 'lazy' ) );
                $image_url = wp_get_attachment_url( $image_id );
                if ( ! $image || ! $image_url ) {
                    continue;
                }
                ?>
                <a href="<?php echo esc_url( $image_url ); ?>" target="_blank" rel="noopener" aria-label="Xem ảnh đính kèm">
                    <?php echo $image; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by WordPress. ?>
                </a>
            <?php endforeach; ?>
        </div>
    <?php endif; ?>
    <div class="oss-feed-footer">
        <?php echo get_avatar( $item['author_id'], 32, '', '', array( 'extra_attr' => 'loading="lazy"' ) ); ?>
        <?php if ( $author['url'] ) : ?>
            <a href="<?php echo esc_url( $author['url'] ); ?>"><?php echo esc_html( $author['name'] ); ?></a>
        <?php else : ?>
            <span><?php echo esc_html( $author['name'] ); ?></span>
        <?php endif; ?>
        <a class="oss-feed-read" href="<?php echo esc_url( $item['url'] ); ?>">Xem bài đăng</a>
    </div>
</article>
